@app.get('/api/csrf')
def csrf():
    import secrets
    token = session.get('csrf_token')
    if not token:
        token = secrets.token_urlsafe(32)
        session['csrf_token'] = token
    session.permanent = True
    return jsonify(csrf_token=token)


@app.get('/api/me')
def me():
    user = user_from_session()
    if not user:
        return jsonify(user=None)
    if user['is_banned']:
        session.clear()
        return jsonify(user=None), 403
    return jsonify(user=public_user(user))


def validate_credentials(username, password):
    if not re.fullmatch(r'[A-Za-z0-9_.-]{3,20}', username or ''):
        return 'Логин должен содержать 3–20 символов: латиницу, цифры, точку, дефис или подчёркивание.'
    if not isinstance(password, str) or not 10 <= len(password) <= 128:
        return 'Пароль должен содержать от 10 до 128 символов.'
    return None


@app.post('/api/register')
@require_csrf
def register():
    data = request.get_json(silent=True) or {}
    username, password = str(data.get('username', '')).strip(), data.get('password', '')
    error = validate_credentials(username, password)
    if error:
        return jsonify(error=error), 400
    try:
        cur = db().execute('INSERT INTO users(username,password_hash,avatar,role) VALUES(?,?,? ,\'user\')',
                           (username, generate_password_hash(password), str(data.get('avatar', '🎮'))[:16]))
        db().commit()
    except sqlite3.IntegrityError:
        return jsonify(error='Такой логин уже занят.'), 409
    session.clear()
    session['user_id'] = cur.lastrowid
    import secrets
    session['csrf_token'] = secrets.token_urlsafe(32)
    session.permanent = True
    return jsonify(user=public_user(user_from_session()), csrf_token=session['csrf_token']), 201


@app.post('/api/login')
@require_csrf
def login():
    data = request.get_json(silent=True) or {}
    username, password = str(data.get('username', '')).strip(), data.get('password', '')
    row = db().execute('SELECT * FROM users WHERE username=? COLLATE NOCASE', (username,)).fetchone()
    if not row or not check_password_hash(row['password_hash'], password if isinstance(password, str) else ''):
        return jsonify(error='Неверный логин или пароль.'), 401
    if row['is_banned']:
        return jsonify(error='Аккаунт заблокирован.'), 403
    session.clear()
    session['user_id'] = row['id']
    import secrets
    session['csrf_token'] = secrets.token_urlsafe(32)
    session.permanent = True
    return jsonify(user=public_user(user_from_session()), csrf_token=session['csrf_token'])


