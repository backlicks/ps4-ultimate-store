@app.post('/api/admin/catalog')
@require_roles('admin', 'owner')
@require_csrf
def add_catalog_item():
    data = request.get_json(silent=True) or {}
    values = catalog_payload(data)
    if not values[0] or not values[6]:
        return jsonify(error='Название и ссылка обязательны.'), 400
    cur = db().execute('INSERT INTO catalog(name,category,description,version,compatibility,source,url,icon) VALUES(?,?,?,?,?,?,?,?)', values)
    db().commit()
    return jsonify(id=cur.lastrowid), 201


@app.patch('/api/admin/catalog/<int:item_id>')
@require_roles('admin', 'owner')
@require_csrf
def edit_catalog_item(item_id):
    data = request.get_json(silent=True) or {}
    current = db().execute('SELECT * FROM catalog WHERE id=?', (item_id,)).fetchone()
    if not current:
        return jsonify(error='Запись не найдена.'), 404
    merged = {'name': current['name'], 'category': current['category'], 'desc': current['description'],
              'version': current['version'], 'compat': current['compatibility'], 'source': current['source'],
              'url': current['url'], 'icon': current['icon']}
    merged.update(data)
    values = catalog_payload(merged)
    if not values[0] or not values[6]:
        return jsonify(error='Название и ссылка обязательны.'), 400
    db().execute('UPDATE catalog SET name=?,category=?,description=?,version=?,compatibility=?,source=?,url=?,icon=? WHERE id=?', (*values, item_id))
    db().commit()
    return jsonify(ok=True)


