def db():
    if 'db' not in g:
        g.db = sqlite3.connect(DB_PATH)
        g.db.row_factory = sqlite3.Row
        g.db.execute('PRAGMA foreign_keys = ON')
    return g.db


@app.teardown_appcontext
def close_db(_error=None):
    conn = g.pop('db', None)
    if conn is not None:
        conn.close()


def init_db():
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    conn.executescript('''
    CREATE TABLE IF NOT EXISTS users (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      username TEXT NOT NULL COLLATE NOCASE UNIQUE,
      password_hash TEXT NOT NULL,
      avatar TEXT NOT NULL DEFAULT '🎮',
      role TEXT NOT NULL DEFAULT 'user' CHECK(role IN ('user','admin','owner')),
      is_banned INTEGER NOT NULL DEFAULT 0,
      created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
    CREATE TABLE IF NOT EXISTS catalog (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      name TEXT NOT NULL,
      category TEXT NOT NULL DEFAULT 'Другое',
      description TEXT NOT NULL DEFAULT '',
      version TEXT NOT NULL DEFAULT '',
      compatibility TEXT NOT NULL DEFAULT '',
      source TEXT NOT NULL DEFAULT '',
      url TEXT NOT NULL DEFAULT '',
      icon TEXT NOT NULL DEFAULT '📦',
      created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
    ''')
    conn.commit()

    # Bootstrap owner and admin from Render environment variables. Existing accounts are not overwritten.
    for prefix, role in [('OWNER', 'owner'), ('ADMIN', 'admin')]:
        username = os.getenv(f'{prefix}_USERNAME', '').strip()
        password = os.getenv(f'{prefix}_PASSWORD', '')
        if username and password:
            if len(password) < 12:
                raise RuntimeError(f'{prefix}_PASSWORD must contain at least 12 characters')
            conn.execute('INSERT OR IGNORE INTO users(username,password_hash,role) VALUES(?,?,?)',
                         (username, generate_password_hash(password), role))
    conn.commit()

    # Seed catalogue only when empty.
    count = conn.execute('SELECT COUNT(*) FROM catalog').fetchone()[0]
    catalog_file = BASE_DIR / 'catalog.json'
    if count == 0 and catalog_file.exists():
        try:
            items = json.loads(catalog_file.read_text(encoding='utf-8'))
            if isinstance(items, dict):
                items = items.get('apps', [])
            for item in items if isinstance(items, list) else []:
                conn.execute('''INSERT INTO catalog(name,category,description,version,compatibility,source,url,icon)
                    VALUES(?,?,?,?,?,?,?,?)''', (
                    str(item.get('name', 'Без названия')),
                    str(item.get('category', 'Другое')),
                    str(item.get('desc', item.get('description', ''))),
                    str(item.get('version', '')),
                    str(item.get('compat', item.get('compatibility', ''))),
                    str(item.get('source', '')),
                    str(item.get('url', '')),
                    str(item.get('icon', '📦')),
                ))
            conn.commit()
        except (ValueError, OSError):
            app.logger.exception('Could not seed catalog.json')
    conn.close()


