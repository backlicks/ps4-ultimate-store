@app.patch('/api/admin/users/<int:user_id>')
@require_roles('admin', 'owner')
@require_csrf
def update_user(user_id):
    data = request.get_json(silent=True) or {}
    target = db().execute('SELECT * FROM users WHERE id=?', (user_id,)).fetchone()
    if not target:
        return jsonify(error='Пользователь не найден'), 404
    actor_role = g.current_user['role']
    if target['role'] == 'owner':
        return jsonify(error='Аккаунт владельца нельзя изменять через эту операцию.'), 403
    if target['role'] == 'admin' and actor_role != 'owner':
        return jsonify(error='Только владелец может управлять администраторами.'), 403
    if 'role' in data:
        if actor_role != 'owner':
            return jsonify(error='Только владелец может менять роли.'), 403
        new_role = data['role']
        if new_role not in ('user', 'admin'):
            return jsonify(error='Допустимые роли: user или admin.'), 400
        db().execute('UPDATE users SET role=? WHERE id=?', (new_role, user_id))
    if 'is_banned' in data:
        db().execute('UPDATE users SET is_banned=? WHERE id=?', (1 if data['is_banned'] else 0, user_id))
    db().commit()
    row = db().execute('SELECT id,username,avatar,role,is_banned,created_at FROM users WHERE id=?', (user_id,)).fetchone()
    return jsonify(user=public_user(row))


@app.delete('/api/admin/users/<int:user_id>')
@require_roles('admin', 'owner')
@require_csrf
def delete_user(user_id):
    target = db().execute('SELECT * FROM users WHERE id=?', (user_id,)).fetchone()
    if not target:
        return jsonify(error='Пользователь не найден'), 404
    if target['role'] == 'owner' or (target['role'] == 'admin' and g.current_user['role'] != 'owner'):
        return jsonify(error='Недостаточно прав для удаления этого аккаунта.'), 403
    if target['id'] == g.current_user['id']:
        return jsonify(error='Нельзя удалить текущий аккаунт.'), 400
    db().execute('DELETE FROM users WHERE id=?', (user_id,))
    db().commit()
    return jsonify(ok=True)


