def user_from_session():
    uid = session.get('user_id')
    if not uid:
        return None
    return db().execute('SELECT id,username,avatar,role,is_banned,created_at FROM users WHERE id=?', (uid,)).fetchone()


def require_login(fn):
    @wraps(fn)
    def wrapped(*args, **kwargs):
        user = user_from_session()
        if not user:
            return jsonify(error='Требуется вход в аккаунт'), 401
        if user['is_banned']:
            session.clear()
            return jsonify(error='Аккаунт заблокирован'), 403
        g.current_user = user
        return fn(*args, **kwargs)
    return wrapped


def require_roles(*roles):
    def decorator(fn):
        @wraps(fn)
        @require_login
        def wrapped(*args, **kwargs):
            if g.current_user['role'] not in roles:
                return jsonify(error='Недостаточно прав'), 403
            return fn(*args, **kwargs)
        return wrapped
    return decorator


def require_csrf(fn):
    @wraps(fn)
    def wrapped(*args, **kwargs):
        expected = session.get('csrf_token')
        supplied = request.headers.get('X-CSRF-Token', '')
        if not expected or not supplied or not __import__('hmac').compare_digest(expected, supplied):
            return jsonify(error='CSRF-проверка не пройдена. Обнови страницу и попробуй снова.'), 403
        return fn(*args, **kwargs)
    return wrapped


def public_user(row):
    return {'id': row['id'], 'username': row['username'], 'avatar': row['avatar'], 'role': row['role'],
            'is_banned': bool(row['is_banned']), 'created_at': row['created_at']}


